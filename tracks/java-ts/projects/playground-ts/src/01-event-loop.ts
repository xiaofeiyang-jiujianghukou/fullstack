console.log('1  同步开始')

// 宏任务（macrotask）：即便延时 0，也要等整个同步栈清空
setTimeout(() => console.log('2  setTimeout 0ms'), 0)

// 微任务（microtask）：优先级高于宏任务
Promise.resolve().then(() => console.log('3  Promise.then'))

queueMicrotask(() => console.log('4  queueMicrotask'))

// async 函数体是「同步执行」的，直到遇见第一个 await
void (async () => {
  console.log('5  async 函数体（同步！）')
  await null // 这一行之后的代码被切成微任务
  console.log('6  await 之后')
})()

console.log('7  同步结束')

/**
 * 关键差异（对照你的 Java 直觉）：
 *
 * - Java：`new Thread(...).start()` 真的并行，靠 OS 调度抢占。
 *   JS：只有一个线程。所谓「异步」是把回调排进队列，等当前调用栈清空后再取。
 *
 * - setTimeout(fn, 0) 不是「立刻执行」，是「尽快排队」。同步代码不跑完，它永远轮不到。
 *
 * - 微任务队列会在每次宏任务之间「一次性清空」，所以 Promise 总是快过 setTimeout。
 *
 * - `await` 不阻塞线程（不同于 Java 的 Thread.sleep / Future.get），
 *   它是把函数剩余部分注册为微任务，然后立即把控制权交还给事件循环。
 */

